def _amp_def() -> Circuit:
    """Tiny Sub-Circuit: VCC-biased BJT inverter.  Two ports: IN, OUT.
    VCC and GND flow as implicit globals."""
    amp = Circuit("amp", desc="single-BJT inverter (test fixture)",
                  ports=["IN", "OUT"])
    amp.add_model_lib(STANDARD_MODEL_LIB)
    amp.add(R("R1", "IN", "n_base", value="10k"))
    amp.add(R("R2", "VCC", "OUT", value="1k"))
    amp.add(NPN("Q1", c="OUT", b="n_base", e="GND"))
    return amp


def _base_top() -> Circuit:
    """Canonical top-level: one amp instance + supplies + load."""
    top = Circuit("hierarchy", desc="H2 fixture root")
    top.add_model_lib(STANDARD_MODEL_LIB)
    top.add(V("VCC_SRC", "VCC", "GND", dc=12))
    top.add(V("V_IN", "AUDIO_IN", "GND", dc=0.7))
    top.add(_amp_def().instance("U_amp1",
                                IN="AUDIO_IN", OUT="AUDIO_OUT"))
    top.add(R("R_LOAD", "AUDIO_OUT", "GND", value="1k"))
    return top


def _list_root_sheets(kicad) -> list[dict]:
    r = kicad.run_python(
        "import klicad_native_hierarchy as h; h.list_sheets()"
    )
    assert r.ok, r.exception_traceback
    return [s for s in ast.literal_eval(r.result_repr) if int(s.get("depth", 0)) == 1]


def _list_pins_for_sheet(kicad, sheet_uuid: str) -> list[dict]:
    r = kicad.run_python(
        f"import klicad_native_hierarchy as h; h.list_sheet_pins({sheet_uuid!r})"
    )
    assert r.ok, r.exception_traceback
    return ast.literal_eval(r.result_repr)


def _list_all_symbols(kicad) -> list[dict]:
    r = kicad.run_python(
        "import klicad_native_schematic_state as ss; ss.list_symbols()"
    )
    assert r.ok, r.exception_traceback
    return ast.literal_eval(r.result_repr)


def _by_ref(rows: list[dict]) -> dict[str, dict]:
    return {row["ref"]: row for row in rows if not row["ref"].startswith("#")}


def _reset_to(kicad, c: Circuit) -> dict:
    return to_schematic(c, SCH, kicad=kicad, mode="replace")


