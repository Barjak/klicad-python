class TestMultiInstanceSharing:
    def test_two_instances_same_file_one_screen(self, kicad):
        amp = _amp_def()
        c = Circuit("hierarchy")
        c.add_model_lib(STANDARD_MODEL_LIB)
        c.add(V("VCC_SRC", "VCC", "GND", dc=12))
        c.add(V("V_IN1", "IN1", "GND", dc=0.7))
        c.add(V("V_IN2", "IN2", "GND", dc=0.7))
        c.add(R("RL1", "OUT1", "GND", value="1k"))
        c.add(R("RL2", "OUT2", "GND", value="1k"))
        c.add(amp.instance("U1", IN="IN1", OUT="OUT1"))
        c.add(amp.instance("U2", IN="IN2", OUT="OUT2"))
        _reset_to(kicad, c)

        sheets = _list_root_sheets(kicad)
        assert len(sheets) == 2
        # Both point at the same child .kicad_sch
        files = {s["file_name"] for s in sheets}
        assert files == {"amp.kicad_sch"}

    def test_body_parts_emitted_only_once(self, kicad):
        """The shared SCH_SCREEN means R1/R2/Q1 exist once across the
        hierarchy, not twice — verify by counting refs scoped to the
        child sheet_path (any instance's path will do)."""
        amp = _amp_def()
        c = Circuit("hierarchy")
        c.add_model_lib(STANDARD_MODEL_LIB)
        c.add(V("VCC_SRC", "VCC", "GND", dc=12))
        c.add(V("V_IN1", "IN1", "GND", dc=0.7))
        c.add(V("V_IN2", "IN2", "GND", dc=0.7))
        c.add(R("RL1", "OUT1", "GND", value="1k"))
        c.add(R("RL2", "OUT2", "GND", value="1k"))
        c.add(amp.instance("U1", IN="IN1", OUT="OUT1"))
        c.add(amp.instance("U2", IN="IN2", OUT="OUT2"))
        _reset_to(kicad, c)

        rows = _list_all_symbols(kicad)
        # Count R1 across all hierarchy paths.  Should be 2 (one entry
        # per SCH_SHEET_PATH that includes the shared SCH_SCREEN), but
        # the underlying kiid is the same.
        r1_rows = [r for r in rows if r["ref"] == "R1"]
        # KiCad lists each path the symbol appears under.
        assert len(r1_rows) >= 1
        # All R1 rows share the same kiid (one screen, multiple paths)
        kiids = {r["kiid"] for r in r1_rows}
        assert len(kiids) == 1


