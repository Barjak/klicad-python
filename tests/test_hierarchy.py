class TestSanitization:
    def test_simple(self):
        assert _sanitize_subckt_filename("amp") == "amp"
        assert _sanitize_subckt_filename("amp_v1") == "amp_v1"

    def test_slashes_and_punctuation(self):
        assert _sanitize_subckt_filename("amp/v1") == "amp_v1"
        assert _sanitize_subckt_filename("audio.front-end") == "audio_front_end"

    def test_unicode_rejected(self):
        # Non-ASCII chars collapse; we strip leading/trailing underscores.
        # The result still has to be non-empty.
        with pytest.raises(ValueError, match="sanitizes to empty"):
            _sanitize_subckt_filename("αβγ")
        with pytest.raises(ValueError):
            _sanitize_subckt_filename("////")

    def test_collision_detection(self):
        # Two definitions that collapse to the same filename → raise
        a = Circuit("amp/v1", ports=["IN", "OUT"])
        b = Circuit("amp_v1", ports=["IN", "OUT"])
        with pytest.raises(ValueError, match="collision"):
            _check_sanitization_collisions([a, b])

    def test_no_collision_for_same_circuit_referenced_twice(self):
        # Same Sub-Circuit object instantiated multiple times collapses
        # to one entry — not a collision.
        a = Circuit("amp", ports=["IN", "OUT"])
        _check_sanitization_collisions([a, a])    # must not raise


