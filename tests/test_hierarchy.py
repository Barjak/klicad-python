class TestSheetInstanceDiff:
    def test_diff_adds_new_instance(self, kicad):
        _reset_to(kicad, _base_top())
        before = _list_root_sheets(kicad)
        assert len(before) == 1

        # Add a second instance of the same amp Sub-Circuit
        c2 = _base_top()
        amp = _amp_def()
        c2.add(amp.instance("U_amp2", IN="AUDIO_IN2", OUT="AUDIO_OUT2"))
        # Need stimulus + load for the new path
        c2.add(V("V_IN2", "AUDIO_IN2", "GND", dc=0.5))
        c2.add(R("R_LOAD2", "AUDIO_OUT2", "GND", value="2.2k"))
        to_schematic(c2, SCH, kicad=kicad, mode="diff")

        after = _list_root_sheets(kicad)
        assert len(after) == 2
        names = {s["name"] for s in after}
        assert names == {"U_amp1", "U_amp2"}

    def test_diff_removes_instance(self, kicad):
        # Start with two instances
        c2 = _base_top()
        amp = _amp_def()
        c2.add(amp.instance("U_amp2", IN="AUDIO_IN2", OUT="AUDIO_OUT2"))
        c2.add(V("V_IN2", "AUDIO_IN2", "GND", dc=0.5))
        c2.add(R("R_LOAD2", "AUDIO_OUT2", "GND", value="2.2k"))
        _reset_to(kicad, c2)
        assert len(_list_root_sheets(kicad)) == 2

        # Remove one: build a circuit without U_amp2
        c3 = _base_top()
        to_schematic(c3, SCH, kicad=kicad, mode="diff")

        after = _list_root_sheets(kicad)
        names = {s["name"] for s in after}
        assert names == {"U_amp1"}


